using System.Globalization;
using System.Text;

namespace ShopVerse.Infrastructure.Seed;

public static class SeedReportWriter
{
    public static string ToMarkdown(SeedReport r, SeedOptions options)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Phase 4 — Catalogue seed report");
        sb.AppendLine();
        sb.AppendLine($"Generated by `dotnet run --project backend/src/ShopVerse.Worker -- seed-catalog` · RNG seed `{options.RandomSeed}` · anchor date `{options.AnchorDateUtc:yyyy-MM-dd}`.");
        sb.AppendLine();
        if (r.AlreadySeeded)
        {
            sb.AppendLine("The database already contained the seed (marker brand present); nothing was changed.");
            return sb.ToString();
        }

        sb.AppendLine("## Counts");
        sb.AppendLine();
        sb.AppendLine("| Item | Count |");
        sb.AppendLine("|---|---:|");
        void Row(string name, object value) => sb.AppendLine($"| {name} | {Convert.ToString(value, CultureInfo.InvariantCulture)} |");
        Row("Categories (12 roots → 3 levels)", r.Categories);
        Row("Brands", r.Brands);
        Row("Sellers", r.Sellers);
        Row("Warehouses", r.Warehouses);
        Row("Products (all statuses)", r.Products);
        Row("Variants", r.Variants);
        Row("Product images (rows)", r.MediaRows);
        Row("Inventory rows", r.InventoryRows);
        Row("Out-of-stock variants", r.OutOfStockVariants);
        Row("Low-stock variants (1–5)", r.LowStockVariants);
        Row("Filterable attributes", r.Attributes);
        Row("Customers", r.Customers);
        Row("Reviews", r.Reviews);
        Row("Review photos", r.ReviewPhotos);
        Row("Questions", r.Questions);
        Row("Answers", r.Answers);
        Row("Artwork files written", r.MediaFilesWritten);
        Row("Seed duration", $"{r.Elapsed.TotalSeconds:F1} s");
        sb.AppendLine();
        sb.AppendLine("## Spot check — 20 random active products");
        sb.AppendLine();
        sb.AppendLine("| # | Product | Brand | Category | Seller | Price | Compare-at | Variants | Images | Reviews | Rating | Stock |");
        sb.AppendLine("|--:|---|---|---|---|--:|--:|--:|--:|--:|--:|---|");
        var i = 1;
        foreach (var s in r.SpotChecks)
        {
            sb.AppendLine($"| {i++} | [{Escape(s.Title)}](/p/{s.Slug}) | {s.Brand} | {Escape(s.Category)} | {Escape(s.Seller)} | {s.Price} | {s.CompareAt ?? "—"} | {s.Variants} | {s.Images} | {s.Reviews} | {s.Rating:0.00} | {s.StockStatus} |");
        }

        return sb.ToString();
    }

    private static string Escape(string text) => text.Replace("|", "\\|");
}
